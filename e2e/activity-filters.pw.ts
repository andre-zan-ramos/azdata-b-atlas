import { test, expect } from './fixtures'

for (const area of ['', '/socios']) for (const width of [375, 1440]) {
  test(`Tipos e CNAEs ${area || 'Empresas'} ${width}`, async ({ page, evidence }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(`/receita-federal/cnpj${area}?modo=mapa&uf=MG`)
    const calls = () => evidence.requests.filter(row => /\/(mapa|mapa\/resultados)\/$/.test(row.path))
    const type = page.getByRole('combobox', { name: 'Tipo de estabelecimento', exact: true })
    await type.fill('Restaurantes')
    await page.getByRole('option', { name: 'Restaurantes', exact: true }).click()
    expect(calls()).toHaveLength(0)
    await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
    await expect.poll(() => calls().length).toBe(2)
    for (const call of calls()) expect(call.params).toMatchObject({ cnaes: '5611201', atividade_escopo: 'principal' })
    await type.fill('Academias')
    await page.getByRole('option', { name: 'Academias', exact: true }).click()
    await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
    await expect.poll(() => calls().length).toBe(4)
    expect(calls().at(-1)?.params.cnaes).toBe('9313100')
    await page.getByText('Demais consultas', { exact: true }).click()
    const codes = page.getByRole('combobox', { name: 'CNAEs específicos', exact: true })
    await codes.fill('Literal')
    await page.getByRole('option', { name: /Literal Receita/ }).click()
    await codes.press('Escape')
    await expect(type).toHaveValue('Seleção personalizada')
    await expect(page.getByRole('button', { name: 'Remover 0010100' })).toBeVisible()
    expect(calls()).toHaveLength(4)
    await page.getByRole('button', { name: 'Remover 9313100' }).click()
    await page.getByText('Demais consultas', { exact: true }).click()
    await page.getByLabel('Início de atividade: de', { exact: true }).fill('2025-01-01')
    await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
    await expect.poll(() => calls().length).toBe(6)
    expect(calls().at(-1)?.params).toMatchObject({ cnaes: '0010100', inicio_atividade_de: '2025-01-01' })
    const dimensions = await page.evaluate(() => [document.documentElement.clientWidth, document.documentElement.scrollWidth])
    expect(dimensions[1]).toBeLessThanOrEqual(dimensions[0] + 1)
    await page.screenshot({ path: `test-results/activity-${area ? 'socios' : 'empresas'}-${width}.png`, fullPage: true })
  })
}
